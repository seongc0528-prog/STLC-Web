-- ================================================================
-- 성경 퀴즈 공지 일괄 삭제
--
-- 홈페이지에서 퀴즈를 올리고 성도가 댓글로 답을 달던 운영을 더 하지 않기로 했다.
-- 공지사항에 쌓인 퀴즈 글(제목 "성경 단어 퀴즈 (…)" · 옛 제목 "그림연상 성경퀴즈 (…)")을
-- 모두 지운다. 댓글(notice_comments)은 on delete cascade 로 함께 사라진다.
--
-- 첨부 이미지 파일까지 지우려면 Storage 쪽을 따로 비워야 한다 —
-- STLC_Web/scripts/delete-quiz-notices.mjs 가 파일을 먼저 지우고 이 조건과
-- 같은 행을 지운다. 이 마이그레이션은 스크립트를 돌리지 않았을 때를 위한 안전망이고,
-- 이미 지웠다면 아무 행도 걸리지 않는다.
-- ================================================================

delete from public.notices
where title like '성경 단어 퀴즈%'
   or title like '그림연상 성경퀴즈%';
